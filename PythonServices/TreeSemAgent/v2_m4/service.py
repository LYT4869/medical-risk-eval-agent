"""Doctor-triggered *simulation* of a fixed LIS event; M3 Run shared as-is.

The official event is never generated by an LLM/Agent tool proposal. The
doctor's authenticated test endpoint replays the server's fixed EV-001 fixture.
Graph Checkpointer contains only Run and source reference IDs, not patient text.
"""
from __future__ import annotations

from pathlib import Path
from typing import TypedDict

from langgraph.checkpoint.sqlite import SqliteSaver
from langgraph.graph import START, END, StateGraph

from v2_m1.run_store import WorkflowConflict
from v2_m2.gateway_adapter import GatewayDoctorClient
from .policy import validate_event_fixture, verify_overlay, verify_report_admission


class M4State(TypedDict, total=False):
    run_id: str
    phase: str
    seeded_event_id: str
    correction_event_id: str
    affected_statement_ids: list[str]
    source_current: str
    followup_issue: str


def build_graph(doctor: GatewayDoctorClient, checkpointer):
    def authorize(state: M4State):
        status = doctor.status(state["run_id"])
        if (status["classification"] != "SIM" or
                status["fixture_id"] != "P001" or
                status["status"] not in ("contract_confirmed", "draft_ready")):
            raise WorkflowConflict("M4 requires a confirmed P001 synthetic Run")

    def stage(state: M4State) -> dict:
        authorize(state)
        history = doctor.stage_m4_history(state["run_id"])
        if history.get("event_id") != "M4-HISTORY":
            raise WorkflowConflict("historical fixture stage mismatch")
        return {"phase": "history_staged", "seeded_event_id": "M4-HISTORY"}

    def apply(state: M4State) -> dict:
        authorize(state)
        expected = validate_event_fixture()
        correction = doctor.apply_m4_simulated_correction(state["run_id"])
        if (correction.get("event_id") != expected["event_id"] or
                correction.get("current") != expected["new"] or
                correction.get("previous") != expected["old"] or
                correction.get("current_hb_g_l") != 130 or
                correction.get("previous_hb_g_l") != 110):
            raise WorkflowConflict("correction event ID or values changed")
        return {"phase": "correction_applied",
                "correction_event_id": "EV-001",
                "affected_statement_ids": ["S-04"]}

    def project(state: M4State) -> dict:
        authorize(state)
        outcome = verify_overlay(doctor.m4_state(state["run_id"]))
        # Report admission *rejects* old E-004; E-005 is current.
        verify_report_admission(
            doctor.validate_m4_current(state["run_id"], ["E-004"]), ["E-004"], False,
        )
        verify_report_admission(
            doctor.validate_m4_current(state["run_id"], ["E-005"]), ["E-005"], True,
        )
        return {"phase": "impact_recorded",
                "source_current": outcome["current_source"],
                "followup_issue": outcome["followup_issue"]}

    graph = StateGraph(M4State)
    graph.add_node("stage", stage)
    graph.add_node("apply", apply)
    graph.add_node("project", project)
    graph.add_edge(START, "stage")
    graph.add_edge("stage", "apply")
    graph.add_edge("apply", "project")
    graph.add_edge("project", END)
    return graph.compile(checkpointer=checkpointer)


class M4GatewayWorkflow:
    def __init__(self, directory: str | Path, doctor: GatewayDoctorClient):
        root = Path(directory)
        root.mkdir(parents=True, exist_ok=True)
        self.doctor = doctor
        self.checkpoints = str(root / "m4_graph_checkpoints.sqlite3")

    @staticmethod
    def config(run_id: str) -> dict:
        return {"configurable": {"thread_id": f"treesem-v2:m4:{run_id}"}}

    def execute(self, run_id: str, *, explicit_simulated_lis_event: bool = False) -> dict:
        if not explicit_simulated_lis_event:
            raise WorkflowConflict("doctor must explicitly trigger synthetic LIS event")
        validate_event_fixture()
        with SqliteSaver.from_conn_string(self.checkpoints) as saver:
            graph = build_graph(self.doctor, saver)
            config = self.config(run_id)
            snapshot = graph.get_state(config)
            if not snapshot.values:
                graph.invoke({"run_id": run_id, "phase": "approved"},
                             config=config, durability="sync")
            elif snapshot.next:
                graph.invoke(None, config=config, durability="sync")
            result = graph.get_state(config)
        state = result.values
        if result.next or state.get("phase") != "impact_recorded":
            raise WorkflowConflict("M4 source correction did not finish")
        return {
            "run_id": run_id, "phase": state["phase"], "next": list(result.next),
            "correction_event_id": state["correction_event_id"],
            "current_source": state["source_current"],
            "stale_statement_ids": state["affected_statement_ids"],
            "new_issue": state["followup_issue"],
            "projection": self.doctor.m4_state(run_id),
        }
